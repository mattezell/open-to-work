/** The rows of a glyph; anything outside the charset draws as a blank. */
export function glyphRows(char: string): string[] {
  return (GLYPH_ROWS[char] ?? BLANK).split(' ');
}

export function hasGlyph(char: string): boolean {
  return char in GLYPH_ROWS;
}

/** Top-left of a character's cell in the font texture. */
export function glyphCell(char: string): { x: number; y: number } {
  const index = Math.max(0, CHARSET.indexOf(char));
  return { x: (index % GLYPHS_PER_ROW) * CELL_W, y: Math.floor(index / GLYPHS_PER_ROW) * CELL_H };
}

export const TEXTURE_W = GLYPHS_PER_ROW * CELL_W;
export const TEXTURE_H = Math.ceil(CHARSET.length / GLYPHS_PER_ROW) * CELL_H;

/** Width in game pixels of the longest line of `text` at `scale`, trailing spacing trimmed. */
export function textWidth(text: string, scale = 1): number {
  const longest = Math.max(...text.split('\n').map((line) => line.length));
  return longest === 0 ? 0 : (longest * CELL_W - 1) * scale;
}

/**
 * A centre banner: the first line is the title, drawn double size; whatever
 * follows the blank line under it is the smaller body.
 */
export function splitBanner(text: string): { title: string; body: string } {
  const [title = '', ...rest] = text.split('\n');
  return { title, body: rest.join('\n').replace(/^\n+/, '') };
}

